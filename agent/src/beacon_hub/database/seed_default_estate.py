def seed_estate_tables(conn: sqlite3.Connection) -> None:
    """Populate rooms, devices, device_states, nav_nodes, nav_edges, robots, and environment if empty."""
    cur = conn.cursor()

    cur.execute("SELECT COUNT(*) FROM rooms")
    if cur.fetchone()[0] == 0:
        for r in DEFAULT_ROOMS:
            cur.execute(
                "INSERT INTO rooms (id, name, polygon_2d) VALUES (?, ?, ?)",
                (r["id"], r["name"], json.dumps(r["polygon_2d"])),
            )

    cur.execute("SELECT COUNT(*) FROM devices")
    if cur.fetchone()[0] == 0:
        for d in DEFAULT_DEVICES:
            cur.execute(
                """
                INSERT INTO devices (
                    id, wbt_name, wbt_def, domain, proto_type, room_id,
                    translation, rotation, config_json, controller_name
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                """,
                (
                    d["id"],
                    d["wbt_name"],
                    d.get("wbt_def"),
                    d["domain"],
                    d["proto_type"],
                    d.get("room_id"),
                    json.dumps(d["translation"]),
                    json.dumps(d["rotation"]),
                    json.dumps(d["config"]),
                    d["controller_name"],
                ),
            )
            state_json = json.dumps(d["initial_state"])
            cur.execute(
                """
                INSERT INTO device_states (device_id, online, desired_state, reported_state)
                VALUES (?, 1, ?, ?)
                """,
                (d["id"], state_json, state_json),
            )

    cur.execute("SELECT COUNT(*) FROM nav_nodes")
    if cur.fetchone()[0] == 0:
        for n in DEFAULT_NAV_NODES:
            cur.execute(
                """
                INSERT INTO nav_nodes (id, name, room_id, x, y, default_theta, is_dock)
                VALUES (?, ?, ?, ?, ?, ?, ?)
                """,
                (
                    n["id"],
                    n["name"],
                    n["room_id"],
                    n["x"],
                    n["y"],
                    n["default_theta"],
                    1 if n["is_dock"] else 0,
                ),
            )

    cur.execute("SELECT COUNT(*) FROM nav_edges")
    if cur.fetchone()[0] == 0:
        for u, v, blocking_id in DEFAULT_NAV_EDGES:
            cur.execute(
                "INSERT INTO nav_edges (from_node, to_node, blocking_device_id) VALUES (?, ?, ?)",
                (u, v, blocking_id),
            )

    cur.execute("SELECT COUNT(*) FROM robots")
    if cur.fetchone()[0] == 0:
        cur.execute(
            """
            INSERT INTO robots (
                id, name, model, pose_x, pose_y, theta, battery_pct, status,
                task_description, arm_pose, gripper, held_object, target_destination,
                active_waypoints_json, doors_to_clear_json, online
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """,
            (
                "tiago",
                "TIAGo",
                "PAL Robotics TIAGo",
                -3.10,
                -7.62,
                1.5708,
                92.0,
                "Docked",
                "idle",
                "home",
                "open",
                "",
                None,
                "[]",
                "[]",
                1,
            ),
        )

    cur.execute("SELECT COUNT(*) FROM environment_config")
    if cur.fetchone()[0] == 0:
        cur.execute(
            "INSERT INTO environment_config (key, value_json) VALUES (?, ?)",
            ("environment", json.dumps({"time_of_day": "day", "sun_luminosity": 0.85})),
        )

    conn.commit()
