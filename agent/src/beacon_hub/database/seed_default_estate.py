def _make_light(
    dev_id: str,
    wbt_name: str,
    wbt_def: str,
    proto_type: str,
    room_id: str,
    translation: list[float],
    color_rgb: list[float],
    intensity: float,
    radius: float,
) -> dict[str, Any]:
    hex_col = ColorUtils.to_hex(color_rgb)
    brightness = round(min(100.0, (intensity / 3.0) * 100)) if intensity > 0 else 0
    is_on = intensity > 0
    return {
        "id": dev_id,
        "wbt_name": wbt_name,
        "wbt_def": wbt_def,
        "domain": "light",
        "proto_type": proto_type,
        "room_id": room_id,
        "translation": translation,
        "rotation": [0.0, 0.0, 1.0, 0.0],
        "config": {
            "pointLightColor": color_rgb,
            "maxIntensity": 3.0,
            "pointLightRadius": radius,
            "initialIntensity": intensity,
        },
        "controller_name": "LightingBridgeWorker",
        "initial_state": {
            "state": "On" if is_on else "Off",
            "power_state": "on" if is_on else "off",
            "brightness": brightness if is_on else 0,
            "color": hex_col,
            "color_rgb": color_rgb,
            "intensity": intensity,
            "metadata": f"Intensity at {intensity:.1f}",
        },
    }


